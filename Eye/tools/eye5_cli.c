/* Developer tool: convert .eye5 packed recipes into embeddable C bytes.
 * Never required by runtime and not part of the game executable. */
#include "eye5.h"
#include <stdio.h>
#include <string.h>

int main(int argc,char **argv){
    uint8_t buf[EYE5_MAX_PACKET];Eye5Bank bank;size_t n;
    if(argc!=4||strcmp(argv[1],"embed")){
        fputs("usage: eye5_cli embed recipes.eye5 generated.h\n",stderr);return 2;
    }
    FILE *in=fopen(argv[2],"rb");if(!in)return 3;
    n=fread(buf,1,sizeof buf,in);
    if(fgetc(in)!=EOF){fclose(in);return 3;}
    if(ferror(in)||fclose(in)||!eye5_read(buf,n,&bank))return 3;
    FILE *out=fopen(argv[3],"wb");if(!out)return 4;
    fprintf(out,"/* Generated by Eye5 CLI; do not edit by hand. */\n"
                "#ifndef EYE5_RECIPES_EMBED_H\n#define EYE5_RECIPES_EMBED_H\n"
                "static const unsigned char eye5_recipes_embedded[%zu] = {\n",n);
    for(size_t i=0;i<n;++i)fprintf(out,"0x%02x%s%s",buf[i],i+1u<n?",":"",i%12u==11u?"\n":" ");
    fprintf(out,"};\n#define EYE5_EMBEDDED_BYTES %zuu\n#endif\n",n);
    if(fclose(out))return 4;
    printf("EYE5 embedded %u materials in %zu bytes\n",bank.count,n);
    return 0;
}
