#!/usr/bin/env python3
"""Build-time source discovery, no Python at game runtime.
Every modules/<slot>/module.c must export bones_mod_<slot>_create(void*).
Adding a folder means no edits to the central engine or registry source.
"""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
slots = ('eye', 'ear', 'brain', 'skin', 'mouth')
found = [s for s in slots if (root/'modules'/s/'module.c').is_file()]
other = [p.name for p in (root/'modules').iterdir() if p.is_dir() and p.name not in slots]
if other:
    raise SystemExit('Unrecognized slot folders (needs architecture review): '+', '.join(sorted(other)))
text = [
    '/* GENERATED by scripts/gen_registry.py -- DO NOT EDIT. */',
    '#include "../../include/bones/foundation.h"',
]
for name in found:
    text.append('extern BonesSubsystem bones_mod_'+name+'_create(void *context);')
text += [
    'bool bones_register_project_modules(BonesFoundation *f, void *eye_context) {',
    '    BonesSubsystem m;',
    '    if (!f) return false;',
    '    if (!eye_context) return false;',
]
for name in found:
    text.extend([
        '    m=bones_mod_'+name+'_create('+('eye_context' if name=='eye' else 'f')+');',
        '    if (!bones_attach_subsystem(&f->engine,&m)) return false;',
    ])
text += ['    (void)m; (void)eye_context;', '    return true;', '}', '']
out=root/'src/generated/module_registry.c'
out.parent.mkdir(parents=True,exist_ok=True)
out.write_text('\n'.join(text),encoding='utf-8')
print('Modulos registrados:',', '.join(found) or 'ninguno')
